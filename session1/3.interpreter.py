# Instalarea interpretorului Python

# Ce este un interpret Python?
# Un interpret Python este aplicatia care “traduce” codul tau Python in instructiuni
# pe care calculatorul le intelege si le executa pas cu pas.
# Practic, este “motorul” care ruleaza codul tau .py.
# Fara interpret, codul e doar text. Cu el — devine aplicatie functionala.


#  Diferenta dintre interpret si IDE
# - Interpretul (python.exe) -> executa efectiv codul.
# - IDE-ul (ex: PyCharm, VS Code) -> ofera un mediu complet de lucru:
#   editor de cod, debugging, terminal, gestionare de pachete etc.
#   IDE = biroul de lucru | Interpret = motorul care ruleaza codul
