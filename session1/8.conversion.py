# Conversii intre tipuri de date in Python

# Conversie de la int la float:

numar_int = 10
numar_float = float(numar_int)
print(numar_float)

# Conversie de la float la int:

numar_float = 10.5
numar_int = int(numar_float)
print(numar_int)

# Conversie de la string la int:

numar_string = '10'
numar_int = int(numar_string)
print(numar_int)

# Conversie de la int la string:

numar_int = 100
numar_string = str(numar_int)
print(numar_string)

# Conversie de la string la float:

numar_str = '3.14'
numar_float = float(numar_str)
print(type(numar_string))

# Conversie de la boolean la int:

boolean = True
valoare_int = int(boolean)
print(valoare_int)

# Conversie de la int la boolean:

numar_int = -1
boolean = bool(numar_int)
print(boolean)

# Conversie de la float la boolean

numar_float = 0.0
boolean = bool(numar_float)
print(boolean)
