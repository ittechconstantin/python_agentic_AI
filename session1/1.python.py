# -----------------------------------------------------------
# Istoria Python
# -----------------------------------------------------------

# Python a fost creat in 1989 de Guido van Rossum, un programator olandez,
# care voia un limbaj simplu, clar si usor de folosit.
# Prima versiune oficiala a fost lansata in 1991.


# Scopul lui Guido a fost sa creeze un limbaj care sa fie:
# - intuitiv (usor de invatat),
# - expresiv (puternic fara sintaxa complicata),
# - si distractiv de folosit


# -----------------------------------------------------------
# Caracteristici principale ale Python
# -----------------------------------------------------------

#  Sintaxa simpla si curata
#   Codul Python arata aproape ca limba engleza.

#  Dinamism
#   Nu este nevoie sa specifici tipurile de date:
#       x = 10
#       text = "Salut"
#   Python detecteaza tipurile automat in timpul rularii.

#  Librarii extinse
#   Python are peste 450.000 de pachete disponibile pe PyPI.
#   Librarii populare:
#   - Web: Django, Flask, FastAPI
#   - Data Science: NumPy, Pandas, Matplotlib
#   - AI / ML: TensorFlow, PyTorch, Scikit-learn
#   - Automatizare: Selenium, Requests

#  Compatibilitate multi-platforma
#   Ruleaza pe Windows, macOS, Linux si chiar pe Raspberry Pi sau Android.
#   Scrii cod o singura data, il rulezi oriunde.

#  Orientat pe obiecte (dar si procedural)
#   Suporta clase, mostenire, polimorfism,
#   dar poti scrie si cod simplu, procedural.
#   Flexibilitate maxima pentru orice tip de proiect.

#  Community-driven
#   Python are una dintre cele mai mari comunitati open-source din lume.
#   Evenimente globale: PyCon, EuroPython, DjangoCon, SciPy.
#   Comunitatea publica constant PEP-uri (Python Enhancement Proposals)
#   care ghideaza evolutia limbajului.